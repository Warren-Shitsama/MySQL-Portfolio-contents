-- QUESTION 7: Weight Change T01 → T05 (Complete Cases Only)
-- ========================================
WITH complete_cases AS (
    SELECT 
        f1.T00_ID,
        f1.T01_WEIGHT  AS weight_t01,
        f5.T05_WEIGHT  AS weight_t05
    FROM follow_01_data f1
    INNER JOIN follow_02_data f2 ON f1.T00_ID = f2.T00_ID
    INNER JOIN follow_03_data f3 ON f1.T00_ID = f3.T00_ID
    INNER JOIN follow_04_data f4 ON f1.T00_ID = f4.T00_ID
    INNER JOIN follow_05_data f5 ON f1.T00_ID = f5.T00_ID
    WHERE f1.T01_WEIGHT IS NOT NULL 
      AND f5.T05_WEIGHT IS NOT NULL
      AND f1.T01_WEIGHT > 0 
      AND f5.T05_WEIGHT > 0
)
SELECT 
    COUNT(*) AS Participants_With_Complete_Weight_Data,
    
    ROUND(AVG(weight_t05 - weight_t01), 2)           AS Avg_Weight_Change_kg,
    ROUND(MIN(weight_t05 - weight_t01), 1)           AS Min_Change,
    ROUND(MAX(weight_t05 - weight_t01), 1)           AS Max_Change,
    ROUND(STDDEV(weight_t05 - weight_t01), 2)        AS StdDev_Change,
    
    -- % who gained, lost, or stable
    ROUND(SUM(CASE WHEN weight_t05 > weight_t01 + 1 THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 1) AS Pct_Gained_1kg_OrMore,
    ROUND(SUM(CASE WHEN weight_t05 < weight_t01 - 1 THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 1) AS Pct_Lost_1kg_OrMore,
    ROUND(SUM(CASE WHEN ABS(weight_t05 - weight_t01) <= 1 THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 1) AS Pct_Stable_Within_1kg,

    -- Binned changes for histogram
    CASE 
        WHEN weight_t05 - weight_t01 <= -5 THEN '-10 to -5 kg'
        WHEN weight_t05 - weight_t01 <= -3 THEN '-5 to -3 kg'
        WHEN weight_t05 - weight_t01 <= -1 THEN '-3 to -1 kg'
        WHEN weight_t05 - weight_t01 <= 1  THEN '-1 to +1 kg (stable)'
        WHEN weight_t05 - weight_t01 <= 3  THEN '+1 to +3 kg'
        WHEN weight_t05 - weight_t01 <= 5  THEN '+3 to +5 kg'
        ELSE '+5 kg or more'
    END AS Weight_Change_Bin,
    COUNT(*) AS N_In_Bin
FROM complete_cases
GROUP BY Weight_Change_Bin
ORDER BY 
    CASE Weight_Change_Bin
        WHEN '-10 to -5 kg'      THEN 1
        WHEN '-5 to -3 kg'       THEN 2
        WHEN '-3 to -1 kg'       THEN 3
        WHEN '-1 to +1 kg (stable)' THEN 4
        WHEN '+1 to +3 kg'       THEN 5
        WHEN '+3 to +5 kg'       THEN 6
        WHEN '+5 kg or more'     THEN 7
    END;

