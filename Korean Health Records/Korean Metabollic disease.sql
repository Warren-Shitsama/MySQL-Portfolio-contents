    COUNT(*) AS N,
    ROUND(AVG(T03_WAIST), 2) AS Mean_Waist,
    ROUND(AVG(T03_GLU0), 2) AS Mean_Glucose,
    
    -- Pearson correlation coefficient
    ROUND(
        (SUM((T03_WAIST - (SELECT AVG(T03_WAIST) FROM follow_03_data WHERE T03_WAIST IS NOT NULL AND T03_GLU0 IS NOT NULL)) * 
             (T03_GLU0 - (SELECT AVG(T03_GLU0) FROM follow_03_data WHERE T03_WAIST IS NOT NULL AND T03_GLU0 IS NOT NULL)))) /
        (SQRT(SUM(POW(T03_WAIST - (SELECT AVG(T03_WAIST) FROM follow_03_data WHERE T03_WAIST IS NOT NULL AND T03_GLU0 IS NOT NULL), 2))) *
         SQRT(SUM(POW(T03_GLU0 - (SELECT AVG(T03_GLU0) FROM follow_03_data WHERE T03_WAIST IS NOT NULL AND T03_GLU0 IS NOT NULL), 2))))
    , 3) AS Pearson_Correlation_r
    
FROM follow_03_data
WHERE T03_WAIST IS NOT NULL 
  AND T03_GLU0 IS NOT NULL
  AND T03_WAIST > 0
  AND T03_GLU0 > 0;

