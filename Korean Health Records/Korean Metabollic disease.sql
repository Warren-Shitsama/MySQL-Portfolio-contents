-- Q10 : Baseline Insulin Predicts Future Diabetes
-- ========================================

WITH at_risk AS (
    SELECT f1.T00_ID, f1.T01_INS0
    FROM follow_01_data f1
    WHERE f1.T01_GLU0 < 126 AND f1.T01_GLU0 IS NOT NULL AND f1.T01_GLU0 != 66666 AND f1.T01_INS0 != 66666
      AND f1.T01_INS0 IS NOT NULL
),
ever_diabetic AS (
    SELECT DISTINCT T00_ID FROM (
        SELECT T00_ID FROM follow_02_data WHERE T02_GLU0 >= 126
        UNION SELECT T00_ID FROM follow_03_data WHERE T03_GLU0 >= 126
        UNION SELECT T00_ID FROM follow_04_data WHERE T04_GLU0 >= 126
        UNION SELECT T00_ID FROM follow_05_data WHERE T05_GLU0 >= 126
    ) x WHERE T00_ID IN (SELECT T00_ID FROM at_risk)
)
SELECT 
    IF(ed.T00_ID IS NOT NULL, 'Developed_Diabetes', 'Remained_Non_Diabetic') AS Outcome,
    COUNT(*) AS N,
    ROUND(AVG(ar.T01_INS0), 2) AS Avg_Baseline_Insulin,
    ROUND(STDDEV(ar.T01_INS0), 2) AS StdDev,
    ROUND(MIN(ar.T01_INS0), 1) AS Min,
    ROUND(MAX(ar.T01_INS0), 1) AS Max
FROM at_risk ar
LEFT JOIN ever_diabetic ed ON ar.T00_ID = ed.T00_ID
GROUP BY Outcome
ORDER BY Avg_Baseline_Insulin DESC;


























































